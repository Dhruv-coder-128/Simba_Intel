from allauth.account.forms import LoginForm, SignupForm, ResetPasswordForm, ChangePasswordForm, AddEmailForm

class SimbaLoginForm(LoginForm):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        for field in self.fields.values():
            field.widget.attrs['class'] = 'form-input'


